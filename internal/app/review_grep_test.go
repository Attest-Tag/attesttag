// serveArchive serves fx.head as GitHub does: the API redirects to the download host, which serves
// the archive to anybody holding the signed URL. It counts the archives served.
func (rig *reviewRig) serveArchive() *int {
	f, n := rig.gh, new(int)
	f.mux.HandleFunc("GET /repos/acme/web/tarball/{sha}", func(w http.ResponseWriter, r *http.Request) {
		if got := f.permsOf(r); got != readPerms {
			rig.t.Errorf("the archive was asked for with a token for %q, want the read-only %q", got, readPerms)
		}
		w.Header().Set("Location", "https://codeload.github.com/acme/web/legacy.tar.gz/"+r.PathValue("sha")+"?token=SIGNED")
		w.WriteHeader(http.StatusFound)
	})
	f.mux.HandleFunc("GET codeload.github.com/acme/web/legacy.tar.gz/{sha}", func(w http.ResponseWriter, r *http.Request) {
		if a := r.Header.Get("Authorization"); a != "" {
			rig.t.Errorf("the download host was sent the installation token: %q", a)
		}
		if r.PathValue("sha") != reviewHead || r.URL.Query().Get("token") != "SIGNED" {
			rig.t.Errorf("downloaded %s, want the head through the URL GitHub signed", r.URL)
		}
		*n++
		w.Write(tarGz(rig.t, "acme-web-aaaaaaa", archiveFiles(rig.fx.head)...))
	})
	return n
}

// The whole way: the finder greps twice and the verifier once, and the head is downloaded once for
// all three — under the read-only token from the API, bare from the download host. Both tools are
// the finder's and the verifier's, and each grep is in the trace.
func TestReviewEngineGrepsTheHead(t *testing.T) {
	rig := newReviewRig(t, totalsFixture())
	downloads := rig.serveArchive()
	rig.model.finder["general"] = func(n int, q reviewModelReq) reviewModelReply {
		switch n {
		case 0:
			return reviewModelReply{Calls: []reviewCall{{"grep", map[string]any{"pattern": "t.value = 0", "literal": true}}}}
		case 1:
			return reviewModelReply{Calls: []reviewCall{{"grep", map[string]any{"pattern": `func \(t \*Totals\)`, "path": "src"}}}}
		}
		return submitFindings(lockFinding())
	}
	var verifierTools []string
	rig.model.verify = func(q reviewModelReq) reviewModelReply {
		verifierTools = q.Tools
		if len(q.ToolResults) == 0 {
			return reviewModelReply{Calls: []reviewCall{{"grep", map[string]any{"pattern": "mu.Lock"}}}}
		}
		return verdict("confirmed", 90, candidateOf(q).Severity)
	}
	out, err := rig.run(rig.spec("general"))
	if err != nil {
		t.Fatal(err)
	}
	if *downloads != 1 {
		t.Errorf("the head was downloaded %d times, want once for the whole run", *downloads)
	}
	finds := rig.model.requests("finder")
	if !slices.Contains(finds[0].Tools, "grep") || !slices.Contains(finds[0].Tools, "file_history") {
		t.Errorf("the finder's tools are %v", finds[0].Tools)
	}
	if !slices.Contains(verifierTools, "grep") || !slices.Contains(verifierTools, "file_history") || slices.Contains(verifierTools, "list_files") {
		t.Errorf("the verifier's tools are %v", verifierTools)
	}
	if res := strings.Join(finds[1].ToolResults, "\n"); !strings.Contains(res, "src/other.go:4: t.value = 0") {
		t.Errorf("the finder's grep did not find the line at the head:\n%s", res)
	}
	if res := strings.Join(finds[2].ToolResults, "\n"); !strings.Contains(res, "src/totals.go:11: func (t *Totals) Add(n int) {") ||
		!strings.Contains(res, "src/totals.go:16: func (t *Totals) Get() int {") {
		t.Errorf("a regular expression under a path did not find both methods:\n%s", res)
	}
	greps := 0
	for _, s := range out.Trace {
		if s.Tool == "grep" {
			greps++
			if s.Error || !strings.Contains(s.Result, "(the pull request's head)") {
				t.Errorf("a grep's trace line is %+v", s)
			}
		}
	}
	if greps != 3 {
		t.Errorf("the trace holds %d greps, want 3: %+v", greps, out.Trace)
	}
	for _, s := range rig.gh.sent() {
		if strings.Contains(s, "tarball") && !strings.HasPrefix(s, "GET /repos/acme/web/tarball/"+reviewHead) {
			t.Errorf("the archive was asked for as %s, want the head's commit", s)
		}
	}
}

