// The archive is read at a commit and nowhere else, and its redirect is followed only to where GitHub
// serves archives from.
func TestReviewGitHubArchiveIsHeldToTheCommit(t *testing.T) {
	c, f := reviewGitHubFixture(t)
	for _, tc := range []struct {
		rel  string
		want bool
	}{
		{"tarball/" + reviewHead, true},
		{"tarball/main", false},
		{"tarball/" + reviewHead + "/x", false},
		{"zipball/" + reviewHead, false},
		{"commits?sha=" + reviewBase + "&path=src%2Fa.go&per_page=10", true},
		{"commits?sha=" + reviewBase + "&author=someone", false},
		{"commits/" + reviewBase, false},
	} {
		u, _ := url.Parse(c.base + "/repos/acme/web/" + tc.rel)
		if err := c.allow("GET", u); (err == nil) != tc.want {
			t.Errorf("GET %s: allowed %v, want %v (%v)", tc.rel, err == nil, tc.want, err)
		}
	}
	if _, err := c.Archive(context.Background(), "main"); err == nil {
		t.Error("an archive of a branch name was asked for")
	}
	f.mux.HandleFunc("GET /repos/acme/web/tarball/{sha}", func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Location", "https://downloads.example.com/acme/web.tar.gz")
		w.WriteHeader(http.StatusFound)
	})
	f.mux.HandleFunc("GET downloads.example.com/", func(w http.ResponseWriter, r *http.Request) {
		t.Errorf("the redirect to another host was followed, with Authorization %q", r.Header.Get("Authorization"))
	})
	if _, err := c.Archive(context.Background(), reviewHead); err == nil || !strings.Contains(err.Error(), "not where GitHub serves archives from") {
		t.Errorf("err = %v, want the redirect refused", err)
	}
}
