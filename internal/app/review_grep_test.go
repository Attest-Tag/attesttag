// Past any cap the copy stops where it got to and says why, so every answer from it can say it was
// partial; a download that breaks before any file was read is an error instead.
func TestReviewHeadIndexStopsAtItsCaps(t *testing.T) {
	var entries []archiveEntry
	for i := range 5 {
		entries = append(entries, archiveEntry{name: fmt.Sprintf("src/f%d.go", i), body: strings.Repeat("package f // padding\n", 50)})
	}
	arch := tarGz(t, "acme-web-aaaaaaa", entries...)
	keep := grepRun().grepKeeps
	for _, tc := range []struct {
		name  string
		caps  reviewIndexCaps
		files int
		why   string
	}{
		{"files", reviewIndexCaps{download: 1 << 30, kept: 1 << 30, files: 2, unpacked: 1 << 30, fileMax: 1 << 20}, 2, "more than the 2 files"},
		{"kept", reviewIndexCaps{download: 1 << 30, kept: 2500, files: 100, unpacked: 1 << 30, fileMax: 1 << 20}, 2, "more text than"},
		{"download", reviewIndexCaps{download: int64(len(arch) / 2), kept: 1 << 30, files: 100, unpacked: 1 << 30, fileMax: 1 << 20}, -1, "larger than"},
		{"unpacked", reviewIndexCaps{download: 1 << 30, kept: 1 << 30, files: 100, unpacked: 4000, fileMax: 1 << 20}, -1, "unpacks to more than"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			ix, err := buildHeadIndex(context.Background(), reviewHead, bytes.NewReader(arch), tc.caps, keep)
			if err != nil {
				t.Fatal(err)
			}
			if !strings.Contains(ix.partial, tc.why) {
				t.Errorf("partial = %q, want it to say %q", ix.partial, tc.why)
			}
			if tc.files >= 0 && len(ix.files) != tc.files {
				t.Errorf("kept %d files, want %d", len(ix.files), tc.files)
			}
			if len(ix.files) >= len(entries) {
				t.Errorf("kept all %d files past a cap", len(ix.files))
			}
			out := ix.search(context.Background(), "acme/web", regexp.MustCompile(`(?m)nothing like this`), "nothing like this", "", 40)
			if !strings.Contains(out, "Only part of the repository was searched: "+ix.partial) || !strings.Contains(out, "find_code") {
				t.Errorf("a search of a partial copy did not say so:\n%s", out)
			}
		})
	}
	if _, err := buildHeadIndex(context.Background(), reviewHead, strings.NewReader("\x1f\x8bnot gzip at all"), reviewIndexLimits, keep); err == nil {
		t.Error("an archive that is not one read as an empty copy")
	}
}

// A search is a regular expression, or plain text when literal; path narrows it to a directory, a
// glob over the path, or a glob over the file's name at any depth; what it shows is capped, and the
// rest is counted, by lines and by files.
func TestReviewGrepSearch(t *testing.T) {
	token := "ghp_" + strings.Repeat("x1", 18)
	arch := tarGz(t, "acme-web-aaaaaaa", archiveFiles(map[string]string{
		"src/auth/check.go":   "package auth\n\nfunc Check(a.b int) {}\nfunc Checkaxb() {}\n",
		"src/auth/check.ts":   "export function Check() {}\n",
		"src/billing/plan.go": "package billing\n\nfunc plan() { auth.Check(1) }\n",
		"lib/keys.go":         "package lib\n\nconst key = \"" + token + "\" // Check\n",
		"web/index.ts":        "Check();\nCheck();\nCheck();\n",
	})...)
	ix, err := buildHeadIndex(context.Background(), reviewHead, bytes.NewReader(arch), reviewIndexLimits, grepRun().grepKeeps)
	if err != nil {
		t.Fatal(err)
	}
	r := &reviewRun{repo: "acme/web", head: reviewHead}
	r.grepIdx.index = ix
	ctx := context.Background()
	grep := func(args string) string {
		t.Helper()
		out, err := r.grep(ctx, args)
		if err != nil {
			t.Fatalf("grep %s: %v", args, err)
		}
		return out
	}

	out := grep(`{"pattern":"a.b"}`)
	if !strings.Contains(out, "src/auth/check.go:3: func Check(a.b int) {}") || !strings.Contains(out, "src/auth/check.go:4: func Checkaxb() {}") {
		t.Errorf("a regular expression did not match as one:\n%s", out)
	}
	out = grep(`{"pattern":"a.b","literal":"true"}`)
	if !strings.Contains(out, "src/auth/check.go:3:") || strings.Contains(out, "check.go:4:") || !strings.Contains(out, "1 matching lines in 1 files") {
		t.Errorf("a literal search matched more than its text:\n%s", out)
	}
	if !strings.HasPrefix(out, "acme/web @ aaaaaaa (the pull request's head): 1 matching lines") {
		t.Errorf("the first line, which the trace keeps, does not say what was searched:\n%s", out)
	}

	for glob, want := range map[string][]string{
		"src/auth":    {"src/auth/check.go", "src/auth/check.ts"},
		"src/**/*.go": {"src/auth/check.go", "src/billing/plan.go"},
		"*.ts":        {"src/auth/check.ts", "web/index.ts"},
		"lib/keys.go": {"lib/keys.go"},
	} {
		out := grep(fmt.Sprintf(`{"pattern":"Check","path":%q}`, glob))
		var got []string
		for _, l := range strings.Split(out, "\n")[1:] {
			if p, _, ok := strings.Cut(l, ":"); ok && strings.Contains(l, ": ") && !slices.Contains(got, p) {
				got = append(got, p)
			}
		}
		if !slices.Equal(got, want) {
			t.Errorf("path %q searched %v, want %v:\n%s", glob, got, want, out)
		}
	}
	if out := grep(`{"pattern":"Check","path":"nowhere/"}`); !strings.Contains(out, "No line of") || !strings.Contains(out, "No text file is under that path") {
		t.Errorf("a path with no files under it was not said to be one:\n%s", out)
	}

	// The copy is raw, and what is shown of it is masked.
	if out := grep(`{"pattern":"const key"}`); strings.Contains(out, token) || !strings.Contains(out, "lib/keys.go:3: const key = \""+reviewMask) {
		t.Errorf("a credential in the head was shown, or its line was not:\n%s", out)
	}

	out = grep(`{"pattern":"Check\\(","max_results":"2"}`)
	if !strings.Contains(out, "6 matching lines in 4 files for \"Check\\\\(\", 2 shown") || !strings.Contains(out, "4 more matches in 2 files") {
		t.Errorf("a capped search did not count what it did not show:\n%s", out)
	}

	for args, want := range map[string]string{
		`{"pattern":"("}`:          "not a regular expression",
		`{"pattern":"  "}`:         "say what to search for",
		`{"pattern":"x","path":5}`: "not a JSON object",
		`{"pattern":"` + strings.Repeat("a", reviewGrepPattern+1) + `"}`: "at most",
	} {
		if _, err := r.grep(ctx, args); err == nil || !strings.Contains(err.Error(), want) {
			t.Errorf("grep %.60s: err = %v, want %q", args, err, want)
		}
	}
}

// What a grep shows fits in one tool result, however many lines match and however long they are.
