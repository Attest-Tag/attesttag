// grep searches a copy of the pull request's head that a review downloads once, as GitHub's archive
// of that commit. These pin what the copy keeps, how far it goes before it says it is partial, what a
// search answers — masked, numbered as read_file numbers, capped — and how the download goes out:
// under the read-only token to GitHub's API, and bare to the host GitHub redirects to.

// archiveEntry is one entry of a test archive: a file unless typ says otherwise.
type archiveEntry struct {
	name, body string
	typ        byte
}

// tarGz is an archive the way GitHub writes one: a global header naming the commit, then every entry
// under one top directory.
func tarGz(t *testing.T, top string, entries ...archiveEntry) []byte {
	t.Helper()
	var buf bytes.Buffer
	gz := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gz)
	must := func(err error) {
		if err != nil {
			t.Fatal(err)
		}
	}
	must(tw.WriteHeader(&tar.Header{Typeflag: tar.TypeXGlobalHeader, Name: "pax_global_header",
		PAXRecords: map[string]string{"comment": reviewHead}}))
	must(tw.WriteHeader(&tar.Header{Typeflag: tar.TypeDir, Name: top + "/", Mode: 0o755}))
	for _, e := range entries {
		h := &tar.Header{Typeflag: tar.TypeReg, Name: top + "/" + e.name, Mode: 0o644, Size: int64(len(e.body))}
		if e.typ != 0 {
			h.Typeflag, h.Size, h.Linkname = e.typ, 0, "elsewhere"
		}
		must(tw.WriteHeader(h))
		if h.Typeflag == tar.TypeReg {
			_, err := tw.Write([]byte(e.body))
			must(err)
		}
	}
	must(tw.Close())
	must(gz.Close())
	return buf.Bytes()
}

// archiveFiles are a path → content map as archive entries, in path order.
func archiveFiles(m map[string]string) []archiveEntry {
	var out []archiveEntry
	for _, k := range slices.Sorted(maps.Keys(m)) {
		out = append(out, archiveEntry{name: k, body: m[k]})
	}
	return out
}

func indexPaths(ix *reviewHeadIndex) []string {
	var out []string
	for _, f := range ix.files {
		out = append(out, f.path)
	}
	return out
}

// grepRun is a run with only what grep's keep rule reads: the settings' ignored paths.
func grepRun(ignore ...string) *reviewRun {
	return &reviewRun{spec: reviewSpec{Settings: review.Effective{IgnorePaths: ignore}}}
}

