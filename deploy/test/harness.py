def template_env(appended, extra_blank=()):
    """An env file as bootstrap.sh leaves it and a person then extends it: a line for every key,
    empty for each key in `appended` (and in `extra_blank`), and those values appended below."""
    lines = ["# throwaway — generated by deploy/test/harness.py, never a real credential"]
    lines += ["%s=" % k for k in extra_blank]
    for k, v in list(SECRETS.items()) + list(PLAIN.items()):
        lines.append("%s=%s" % (k, "" if k in appended else v))
    lines.append("# appended later")
    lines += ["%s=%s" % (k, v) for k, v in appended.items()]
    return "\n".join(lines) + "\n"


def state_with(text):
    state = pathlib.Path(tempfile.mkdtemp(prefix="deploycloud-"))
    (state / "env").write_text(text)
    return state


