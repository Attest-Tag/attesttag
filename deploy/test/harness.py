@scenario("aws: CREATE_DATABASE creates a private RDS and wires DATABASE_URL through")
def _():
    r = run("deploy/aws/fargate.sh", env={"DOMAIN": "bot.example.com",
                                          "CREATE_DATABASE": "1", "ASSUME_YES": "1"})
    ok(r.code == 0, "fargate.sh exited %d\n%s" % (r.code, r.stderr[-900:]))
    create = r.capture("rds-create-db-instance.txt")
    ok(create, "no RDS instance was created")
    ok("--no-publicly-accessible" in create, "the database is reachable from the internet")
    ok("--storage-encrypted" in create, "the database is not encrypted at rest")
    ok("--backup-retention-period 7" in create, "no backups")
    ok("--db-name attesttag" in create, "no initial database was created")

    # Reachable from the task and from nothing else.
    grant = [c for c in r.calls("aws")
             if c[1:3] == ["ec2", "authorize-security-group-ingress"] and "5432" in c]
    ok(grant, "nothing was allowed to reach the database on 5432")
    ok("--source-group" in grant[0], "port 5432 was opened to a CIDR rather than to the task group")

    # The DSN reaches the env file, and from there the task definition, as a secret.
    env_text = (r.state_dir / "env").read_text()
    ok("DATABASE_URL=postgres://attesttag:" in env_text,
       "the DSN was not written back to the env file, so a rerun would create a second database")
    ok(".rds.amazonaws.com:5432/attesttag?sslmode=require" in env_text,
       "the DSN does not require TLS or does not name the instance endpoint")
    td = json.loads(r.capture("taskdef-attesttag-1.json"))
    container = td["containerDefinitions"][0]
    ok("DATABASE_URL" in {s["name"] for s in container["secrets"]},
       "DATABASE_URL never reached the task definition; the deploy would still be on SQLite")
    ok("postgres://" not in json.dumps(container["environment"]),
       "the DSN, which carries a password, was passed as a plain environment value")
    env = {e["name"]: e["value"] for e in container["environment"]}
    ok(env.get("DOCS_S3_URL"), "documents lost their bucket when the rows moved to Postgres")

    # The generated password is never printed, and never reaches the call transcript.
    password = env_text.split("DATABASE_URL=postgres://attesttag:")[1].split("@")[0]
    ok(len(password) >= 16, "the generated password is only %d characters" % len(password))
    ok(password not in r.output, "the generated database password was printed")
    ok(password not in (r.state_dir / "calls.log").read_text(),
       "the generated database password was written to the call transcript")


