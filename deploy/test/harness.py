class Fail(Exception):
    pass


class Run:
    """One invocation of a deploy script, plus everything the fakes recorded about it."""

    def __init__(self, state, script, env, stdout, stderr, code):
        self.state_dir = state
        self.script = script
        self.env = env
        self.stdout = stdout
        self.stderr = stderr
        self.code = code

    @property
    def output(self):
        return self.stdout + self.stderr

    def calls(self, tool=None):
        f = self.state_dir / "calls.log"
        if not f.exists():
            return []
        rows = [json.loads(line) for line in f.read_text().splitlines() if line.strip()]
        return [r for r in rows if tool is None or r[0] == tool]

    def called(self, *words):
        """Was there a call whose argv contains all of these words, in order?"""
        for row in self.calls():
            joined = " ".join(row)
            if all(w in joined for w in words):
                idx = [joined.index(w) for w in words]
                if idx == sorted(idx):
                    return row
        return None

    def count(self, key):
        f = self.state_dir / "state.json"
        if not f.exists():
            return 0
        return json.loads(f.read_text()).get("_counters", {}).get(key, 0)

    def capture(self, name):
        f = self.state_dir / "captures" / name
        return f.read_text() if f.exists() else None

    def captures(self, pattern):
        d = self.state_dir / "captures"
        if not d.exists():
            return []
        return sorted(p.name for p in d.iterdir() if re.search(pattern, p.name))


def env_file(path, drop=(), extra=None):
    lines = ["# throwaway — generated by deploy/test/harness.py, never a real credential"]
    for k, v in list(SECRETS.items()) + list(PLAIN.items()):
        if k in drop:
            continue
        lines.append("%s=%s" % (k, v))
    for k, v in (extra or {}).items():
        lines.append("%s=%s" % (k, v))
    path.write_text("\n".join(lines) + "\n")
    return path


def run(script, *, state=None, env=None, drop=(), extra_env=None, env_extra=None, stdin="",
        tty_answer=None, shell="bash"):
    """Run a deploy script with the fakes on PATH. `state` reuses a previous run's registry."""
    fresh = state is None
    state = state or pathlib.Path(tempfile.mkdtemp(prefix="deploycloud-"))
    # A reused state directory keeps the first run's resources but takes a new env file whenever
    # this run asks for different settings — that is how a scenario runs worker.sh and then the
    # deploy script against the same account with the worker switched on.
    if fresh or drop or env_extra:
        env_file(state / "env", drop=drop, extra=env_extra)

    e = dict(os.environ)
    e["PATH"] = "%s:%s" % (FAKES, e["PATH"])
    e["FAKE_CLOUD_STATE"] = str(state)
    # Always explicit: the scripts default ENV_FILE to the repository's real .env, and a test
    # that fell through to it would read live credentials.
    e["ENV_FILE"] = str(state / "env")
    e.pop("AWS_PROFILE", None)
    e.update(env or {})

    if tty_answer is None:
        # stdin is a closed pipe unless a scenario says otherwise, so `[ -t 0 ]` is
        # deterministically false: the CREATE_DATABASE confirmation must refuse rather than
        # block a whole test run on a prompt nobody is going to answer.
        p = subprocess.run([shell, str(ROOT / script)], cwd=str(ROOT), env=e,
                           input=stdin, capture_output=True, text=True, timeout=120)
        return Run(state, script, e, p.stdout, p.stderr, p.returncode)

    # A real terminal, because that is the only way `[ -t 0 ]` is true and the prompt is
    # reached at all. This is the path a person actually takes.
    import pty
    master, slave = pty.openpty()
    proc = subprocess.Popen([shell, str(ROOT / script)], cwd=str(ROOT), env=e, stdin=slave,
                            stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    os.close(slave)
    os.write(master, tty_answer.encode())
    try:
        stdout, stderr = proc.communicate(timeout=120)
    finally:
        os.close(master)
    return Run(state, script, e, stdout, stderr, proc.returncode)


# ── assertions ───────────────────────────────────────────────────────────────────────────────
def ok(cond, msg):
    if not cond:
        raise Fail(msg)


def scenario(name):
    """Register a scenario. Registration only — main() runs them, so importing this file to
    poke at one scenario does not run all forty."""
    def deco(fn):
        REGISTERED.append((name, fn))
        return fn
    return deco


def no_secret_leaked(r):
    for key, value in SECRETS.items():
        if value in r.output:
            raise Fail("the value of %s appeared in the script output" % key)


def show(r):
    if VERBOSE:
        print("\n--- %s exit=%d ---\n%s\n%s---\n" % (r.script, r.code, r.stdout, r.stderr))


