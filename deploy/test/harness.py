#!/usr/bin/env python3
"""Run deploy/aws/*.sh, deploy/azure/*.sh and deploy/gcp/*.sh against fake CLIs and assert on
what they did.

Usage:  ./deploy/test/run.sh [-v] [name-filter]

Each scenario gets a throwaway env file of obvious fakes and a fresh state directory, with
deploy/test/fakes first on PATH so `aws`, `az`, `gcloud` and `docker` resolve to the recorders.
Nothing here touches a cloud account, the repository's own .env, or the network.

The AWS and Azure scripts are run with whatever bash is first on PATH. On macOS that is 3.2, which
is the oldest they claim to support and the version deploy/aws/worker.sh warns about by name.
The gcp scripts run under zsh, their shebang.
"""
