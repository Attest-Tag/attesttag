def main():
    for name, fn in REGISTERED:
        if FILTER and FILTER not in name:
            continue
        try:
            fn()
            results.append((True, name, ""))
            print("  \033[32mPASS\033[0m  %s" % name)
        except Fail as exc:
            results.append((False, name, str(exc)))
            print("  \033[31mFAIL\033[0m  %s\n        %s" % (name, exc))
        except Exception as exc:  # noqa: BLE001 - a broken fake should read as a failed test
            results.append((False, name, repr(exc)))
            print("  \033[31mERROR\033[0m %s\n        %r" % (name, exc))

    passed = sum(1 for good, _, _ in results if good)
    failed = [(n, m) for good, n, m in results if not good]
    print("\n%d passed, %d failed" % (passed, len(failed)))
    if failed:
        print("\nfailures:")
        for name, msg in failed:
            print("  %s\n    %s" % (name, msg))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
