def spec_of(r):
    import yaml
    body = r.capture("containerapp-spec.yaml")
    ok(body, "no Container Apps spec was captured")
    try:
        return yaml.safe_load(body)
    except Exception as exc:  # noqa: BLE001
        raise Fail("the hand-rolled YAML writer produced something PyYAML cannot parse: %s" % exc)


