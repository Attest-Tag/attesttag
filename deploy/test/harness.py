def fake_gcloud_first():
    # The calls in the gcp scripts that would cost anything are `gcloud run deploy --source .` and
    # `gcloud builds submit .`, which upload this checkout. So the fake has to be the gcloud that
    # resolves, or nothing runs.
    path = "%s:%s" % (FAKES, os.environ["PATH"])
